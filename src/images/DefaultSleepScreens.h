#include <GfxRenderer.h>

#include <cstdint>

// Thresholded 1-bit run-length assets generated from the supplied X3/X4 BMPs.
// A run stores only black pixels, keeping the bundled default screen small.
struct DefaultSleepRun {
  uint16_t x;
  uint16_t width;
};

struct DefaultSleepRow {
  uint16_t firstRun;
  uint16_t runCount;
};

inline void drawBundledDefaultScreen(const GfxRenderer& renderer, const uint16_t width, const uint16_t height,
                                     const DefaultSleepRow* rows, const DefaultSleepRun* runs) {
  for (uint16_t y = 0; y < height; ++y) {
    const DefaultSleepRow row = rows[y];
    for (uint16_t runIndex = 0; runIndex < row.runCount; ++runIndex) {
      const DefaultSleepRun run = runs[row.firstRun + runIndex];
      for (uint16_t offset = 0; offset < run.width; ++offset) renderer.drawPixel(run.x + offset, y);
    }
  }
}

