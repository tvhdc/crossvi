"""Generate CrossVi's compact English-Vietnamese vocabulary table.

The eligible headwords come from the Oxford 3000 PDF supplied for CrossVi,
plus a small curated set of essential grammatical forms such as ``are`` and
``was``. ``wordfreq`` is used only to rank that trusted pool and select exactly
3,000 single-word entries. Definitions and pronunciations prefer
thichhoc-dict and fall back to the corresponding PDF row. Closed-class words
are curated here because WordNet-based dictionaries do not represent their
everyday grammatical senses well.

Data generated by this script is a modified derivative of thichhoc-dict and is
licensed CC BY-SA 4.0. The firmware shows the required attribution in the
Vocabulary activity.
"""

